ALTER TABLE images
 ADD COLUMN IF NOT EXISTS sha256 TEXT NOT NULL DEFAULT '' CHECK (sha256 = '' OR sha256 ~ '^[0-9a-f]{64}$'),
 ADD COLUMN IF NOT EXISTS sha256_size_bytes BIGINT,
 ADD COLUMN IF NOT EXISTS sha256_modified_at TIMESTAMPTZ,
 ADD COLUMN IF NOT EXISTS sha256_computed_at TIMESTAMPTZ;

ALTER TABLE catalog_settings
 ADD COLUMN IF NOT EXISTS hash_index_enabled BOOLEAN NOT NULL DEFAULT TRUE,
 ADD COLUMN IF NOT EXISTS hash_index_rate_mbps INT NOT NULL DEFAULT 50 CHECK (hash_index_rate_mbps BETWEEN 0 AND 1000);
